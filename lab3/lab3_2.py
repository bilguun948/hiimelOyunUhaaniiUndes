# Бүхэл тоонуудын анхны жагсаалтаас тэгш тооны В, сондгой тооны С гэсэн хоёр жагсаалт 
# үүсгээд сондгой утгуудыг өсөхөөр, тэгш утгуудыг буурахаар эрэмбэл.

A = list(map(int, input("Тоонуудыг оруул: ").split()))

B = []
C = []

for x in A:
    if x % 2 == 0:
        B.append(x)
    else:
        C.append(x)

B.sort(reverse=True)
C.sort()

print("Тэгш тоонууд B =", B)
print("Сондгой тоонууд C =", C)
