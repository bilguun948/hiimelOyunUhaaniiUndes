# 9. Тэмдэгт мөртэй ажиллах
# Даалгавар: Хэрэглэгчээс текст оруулж, тухайн текстэн доторх үгсийн тоог тоолох. Зорилго: Тэмдэгт мөртэй ажиллах, давталт болон функц ашиглах.

def word_count(text):
    words = text.split()
    return len(words)

text = input("Текстээ оруулна уу: ")

count = word_count(text)

print("Нийт үгийн тоо:", count)
