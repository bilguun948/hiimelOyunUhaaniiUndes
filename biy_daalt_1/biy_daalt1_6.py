# Элемент олох алгоритм
# Даалгавар: Хэрэглэгчээс жагсаалт оруулж, жагсаалтаас хайж буй элементийг олох эсэхийг шалгаарай.
# Зорилго: Массив доторх элементийг хайх, логик үйлдлүүд ашиглах.

my_list = input("Жагсаалтын элементүүдийг зайгаар тусгаарлан оруулна уу: ").split()

search = input("Хайх элементээ оруулна уу: ")

if search in my_list:
    print("Элемент жагсаалтад байна.")
else:
    print("Элемент жагсаалтад байхгүй.")
