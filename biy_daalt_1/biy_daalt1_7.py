# 7. Хүснэгт үүсгэх
# Даалгавар: Хэрэглэгчээс хүснэгтийн хэмжээг оруулж, N x N хэмжээтэй үржвэрийн хүснэгт үүсгэх.
# Зорилго: Давхар давталт, математикийн үйлдлүүдтэй танилцах.
N = int(input("Хүснэгтийн хэмжээг оруулна уу: "))

for i in range(1, N + 1):
    for j in range(1, N + 1):
        print(i * j, end="\t")
    print()
