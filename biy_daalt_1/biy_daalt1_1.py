# 1. Үндсэн тооцоолол
# Даалгавар: Хэрэглэгчээс хоёр тоо оруулж, эдгээр тоонуудын нийлбэр, 
# үржвэр, ялгаврыг тооцоолж хэвлэ.
# Зорилго: Үндсэн математик үйлдлүүд болон input() функцтэй ажиллаж сурах.

number = int(input("Дурын a тоог оруулна уу? "))
number2 = int(input("Дурын b тоог оруулна уу? "))

sum = number + number2
minus = number - number2
urjih = number * number2

print("Нийлбэр нь", sum)
print("Хасах үйлдэл нь", minus)
print("Үржих үйлдэл нь", urjih)

