#  Тэгш, сондгой тоо ялгах
# Даалгавар: 1-100 хүртэлх бүх тоог хэвлээд, тэгш болон сондгой тоог 
# тусад нь ангилах. 
# Зорилго: Угсарсан нөхцөл ашиглах, жагсаалт болон даталт ашиглах.
tegsh = []
sondgoi = []

for i in range(1, 101):
    print(i)

    if i % 2 == 0:
        tegsh.append(i)
    else:
        sondgoi.append(i)

print("Тэгш тоонууд:")
print(tegsh)

print("Сондгой тоонууд:")
print(sondgoi)
